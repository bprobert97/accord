#!/usr/bin/env python3
"""
Reproduce the data-driven figures (2, 3, 4 and 5) from the ACCORD IEEE TAES paper.

Figure 1 is a flow chart and is not generated by code.

Usage (from the repository root, inside the activated virtual environment):

    python reproduce_figures.py                 # everything
    python reproduce_figures.py --figures 4     # only Figure 4 (single run, fast)
    python reproduce_figures.py --figures 2 3   # only Figures 2 and 3

Simulation outputs are cached on disk, so re-running this script re-uses any data
that already exists and only regenerates the plots. Finished figures are copied to
./paper_figures/.

Requires the --isl-range-km / --no-plots changes to accord_demo.py and mc_demo.py
described in the README section.
"""
import argparse
import os
import shutil
import subprocess
import sys
import warnings
from pathlib import Path

# Must be set before matplotlib is imported anywhere (also inherited by subprocesses),
# so the script runs headless and never blocks on plt.show().
os.environ["MPLBACKEND"] = "Agg"
os.environ["PYTHONWARNINGS"] = "ignore:FigureCanvasAgg is non-interactive:UserWarning"

REPO_ROOT = Path(__file__).resolve().parent
os.chdir(REPO_ROOT)  # the repo scripts use paths relative to the repo root
sys.path.insert(0, str(REPO_ROOT))
warnings.filterwarnings("ignore", message=".*non-interactive.*")

PYTHON = sys.executable
FIG_DIR = REPO_ROOT / "paper_figures"
EXPECTED_MC_RUNS = 40  # NUM_RUNS in mc_demo.py; the paper uses 40 runs per configuration

# Figure 4 settings
FIG4_FILTER = "ekf"
FIG4_ISL_KM = 600
FIG4_SIM_RESULTS = REPO_ROOT / "sim_data" / f"sim_results_{FIG4_FILTER}_walker_{FIG4_ISL_KM}km.npz"

_mc_done: set[tuple[str, int]] = set()


def run(cmd: list[str]) -> None:
    """Run a command from the repo root, aborting the whole script if it fails."""
    print("\n$ " + " ".join(cmd), flush=True)
    subprocess.run(cmd, cwd=REPO_ROOT, check=True)


def ensure_mc_data(filter_type: str, isl_km: int, keep_logging: bool) -> None:
    """
    Run mc_demo.py (random topology) for one filter / ISL range.
    mc_demo.py skips any work whose results are already cached on disk.
    """
    if (filter_type, isl_km) in _mc_done:
        return
    cmd = [PYTHON, "mc_demo.py",
           "--filter-type", filter_type,
           "--isl-range-km", str(isl_km),
           "--no-plots"]
    if not keep_logging:
        cmd.append("--disable-logging")
    run(cmd)
    _mc_done.add((filter_type, isl_km))


def check_runs(results: list, label: str) -> None:
    """Fail loudly if the Monte Carlo results are incomplete (some runs returned None)."""
    if len(results) != EXPECTED_MC_RUNS:
        raise RuntimeError(
            f"{label}: found {len(results)} valid runs, expected {EXPECTED_MC_RUNS}. "
            "Delete that mc_results_*.npz file and re-run to regenerate it."
        )


def publish(src_dir: str, src_name: str, dst_name: str) -> None:
    """Copy a generated figure into ./paper_figures/ under its paper name."""
    FIG_DIR.mkdir(exist_ok=True)
    src = Path(src_dir) / src_name
    if not src.exists():
        raise FileNotFoundError(f"Expected figure was not produced: {src}")
    shutil.copy(src, FIG_DIR / dst_name)
    print(f"  -> {FIG_DIR / dst_name}")


# --------------------------------------------------------------------------- #
# Figures 2 and 3: ISL range comparison (EKF, random topology, 1000 km vs 2000 km)
# --------------------------------------------------------------------------- #
def make_figures_2_and_3(figs: set[int], keep_logging: bool,
                         start_a: int, start_b: int) -> None:
    import matplotlib.pyplot as plt
    ensure_mc_data("ekf", 1000, keep_logging)
    ensure_mc_data("ekf", 2000, keep_logging)

    from src.plotting import isl_mc_comparison as isl
    os.makedirs(isl.OUTPUT_DIR, exist_ok=True)
    res_a = isl.load_results(isl.PATH_A)
    res_b = isl.load_results(isl.PATH_B)
    check_runs(res_a, "EKF 1000 km")
    check_runs(res_b, "EKF 2000 km")

    if 3 in figs:
        isl.plot_reputation_comparison(res_a, res_b,
                                       start_step_a=start_a, start_step_b=start_b)
        publish(isl.OUTPUT_DIR, "reputation_comparison.png",
                "figure3_isl_reputation_comparison.png")
    if 2 in figs:
        isl.plot_kpi_comparison(res_a, res_b)
        publish(isl.OUTPUT_DIR, "kpi_percentage_comparison.pdf",
                "figure2_isl_kpi_comparison.pdf")
        publish(isl.OUTPUT_DIR, "kpi_percentage_comparison.png",
                "figure2_isl_kpi_comparison.png")
    plt.close("all")


# --------------------------------------------------------------------------- #
# Figure 4: Walker-Delta, 600 km ISL, single accord_demo run
# --------------------------------------------------------------------------- #
def make_figure_4() -> None:
    import numpy as np
    import matplotlib.pyplot as plt

    run([PYTHON, "accord_demo.py",
         "--filter-type", FIG4_FILTER,
         "--walker-delta", "True",   # NB: argparse type=bool treats ANY non-empty string as True
         "--isl-range-km", str(FIG4_ISL_KM)])

    if not FIG4_SIM_RESULTS.exists():
        raise FileNotFoundError(
            f"{FIG4_SIM_RESULTS} not found. Has the --isl-range-km / results-path "
            "change been applied to accord_demo.py?")

    with np.load(FIG4_SIM_RESULTS, allow_pickle=True) as data:
        rep_history = data["rep_history"].item()
        faulty_ids = {int(i) for i in data["faulty_ids"]}

    from src.plotting.plotting import plot_aggregated_reputation, calculate_convergence_index

    # plot_aggregated_reputation() only calls plt.show(); neutralise it and save ourselves.
    plt.show = lambda *a, **k: None  # type: ignore[assignment]

    # Same call as the plotting block at the bottom of accord_demo.py
    convergence_idx = calculate_convergence_index(rep_history, compromised_ids=faulty_ids)
    plot_aggregated_reputation(rep_history, compromised_ids=faulty_ids,
                               start_at_full_constellation=False,
                               convergence_index=convergence_idx)

    FIG_DIR.mkdir(exist_ok=True)
    fig = plt.gcf()
    out_png = FIG_DIR / "figure4_walker_delta_reputation.png"
    out_pdf = FIG_DIR / "figure4_walker_delta_reputation.pdf"
    fig.savefig(out_png, dpi=300, bbox_inches="tight")
    fig.savefig(out_pdf, bbox_inches="tight")
    print(f"  -> {out_png}\n  -> {out_pdf}")
    plt.close("all")


# --------------------------------------------------------------------------- #
# Figure 5: filter comparison (EKF vs CKF vs UKF, random topology, 1000 km)
# --------------------------------------------------------------------------- #
def make_figure_5(keep_logging: bool) -> None:
    import matplotlib.pyplot as plt
    for filter_type in ("ekf", "ckf", "ukf"):
        ensure_mc_data(filter_type, 1000, keep_logging)  # EKF 1000 km is shared with Fig 2

    from src.plotting import filter_mc_comparison as fc
    os.makedirs(fc.OUTPUT_DIR, exist_ok=True)
    res_ekf = fc.load_results(fc.PATH_EKF)
    res_ukf = fc.load_results(fc.PATH_UKF)
    res_ckf = fc.load_results(fc.PATH_CKF)
    check_runs(res_ekf, "EKF 1000 km")
    check_runs(res_ukf, "UKF 1000 km")
    check_runs(res_ckf, "CKF 1000 km")

    # Argument order in the repo is (ekf, ukf, ckf)
    fc.plot_kpi_comparison(res_ekf, res_ukf, res_ckf)
    publish(fc.OUTPUT_DIR, "kpi_percentage_comparison.pdf", "figure5_filter_kpi_comparison.pdf")
    publish(fc.OUTPUT_DIR, "kpi_percentage_comparison.png", "figure5_filter_kpi_comparison.png")
    plt.close("all")


def main() -> None:
    parser = argparse.ArgumentParser(description="Reproduce ACCORD paper Figures 2-5.")
    parser.add_argument("--figures", type=int, nargs="+", choices=[2, 3, 4, 5],
                        default=[2, 3, 4, 5], help="Which figures to generate (default: all).")
    parser.add_argument("--logging", action="store_true",
                        help="Keep per-run logging in Monte Carlo runs (slower, bigger logs; "
                             "results are identical).")
    parser.add_argument("--fig3-start-step-1000", type=int, default=0,
                        help="start_step_a passed to plot_reputation_comparison (default 0).")
    parser.add_argument("--fig3-start-step-2000", type=int, default=0,
                        help="start_step_b passed to plot_reputation_comparison (default 0).")
    args = parser.parse_args()
    figs = set(args.figures)

    if figs & {2, 3}:
        make_figures_2_and_3(figs, args.logging,
                             args.fig3_start_step_1000, args.fig3_start_step_2000)
    if 4 in figs:
        make_figure_4()
    if 5 in figs:
        make_figure_5(args.logging)

    print(f"\nDone. Figures are in {FIG_DIR}")


if __name__ == "__main__":
    main()
